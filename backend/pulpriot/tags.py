"""Provenance, uncertainty and grain vocabulary shared by every output.

Every number the API returns travels with a `Tag`: where it came from, how fresh it is and what kind of
uncertainty (if any) it carries. The UI renders these as trust badges (feature A5)."""
from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field

# Provenance (spec section 4 + A5 plain-language classes)
OBSERVED = "OBSERVED"          # reported by a source system (still SYNTHETIC in this workbook; see SYNTHETIC)
SYNTHETIC = "SYNTHETIC"        # generated by the supplied workbook
PROXY = "PROXY"
ASSUMED = "ASSUMED"
ESTIMATED = "ESTIMATED"        # produced by the engine from data
CALCULATED = "CALCULATED"      # arithmetic on reported/estimated values
CENSOR_ADJUSTED = "CENSOR_ADJUSTED"

# Uncertainty
SCENARIO = "SCENARIO"
EVENT_SCENARIO = "EVENT_SCENARIO"
CONFORMAL = "CONFORMAL"

# Grain
OBSERVED_GRAIN = "OBSERVED_GRAIN"
PHASED = "PHASED"
RECONCILED = "RECONCILED"

# Warnings
LOWER_BOUND_ONLY = "LOWER_BOUND_ONLY"
EXTRAPOLATING = "EXTRAPOLATING"
UNITS_SOLD_SIGNAL = "UNITS_SOLD_SIGNAL"
EVENT_SHAPE_UNKNOWN = "EVENT_SHAPE_UNKNOWN"
DATA_QUALITY = "DATA_QUALITY"
FALLBACK_PRIMARY = "FALLBACK_PRIMARY"
STALE = "STALE"


class Tag(BaseModel):
    """Trust badge payload: provenance, freshness, uncertainty type, warnings."""
    provenance: list[str] = Field(default_factory=list)
    as_of: str | None = None                 # timestamp of the data the number rests on
    freshness_days: float | None = None      # age of that data at the as-of moment
    interval_type: str | None = None
    grain_tag: str | None = None
    warnings: list[str] = Field(default_factory=list)
    source: str | None = None                # sheet / function that produced it
    note: str | None = None


def tag(*prov: str, as_of: Any = None, fresh: float | None = None, interval: str | None = None,
        grain: str | None = None, warn: list[str] | None = None, source: str | None = None,
        note: str | None = None) -> dict:
    """Plain-dict tag for use inside engine outputs."""
    return Tag(provenance=list(prov), as_of=None if as_of is None else str(as_of), freshness_days=fresh,
               interval_type=interval, grain_tag=grain, warnings=warn or [], source=source,
               note=note).model_dump()


# Plain-language class for the A5 badge: "real fact, calculation, or estimate"
def trust_class(prov: list[str]) -> str:
    p = set(prov)
    if p & {ASSUMED}:
        return "ASSUMPTION"
    if p & {ESTIMATED, CENSOR_ADJUSTED, PROXY}:
        return "ESTIMATE"
    if p & {CALCULATED}:
        return "CALCULATION"
    return "REPORTED"
